function cr(p0,p1,p2,p3,u){          /* Catmull-Rom, one component */
  const u2=u*u, u3=u2*u;
  return 0.5*((2*p1)+(-p0+p2)*u+(2*p0-5*p1+4*p2-p3)*u2+(-p0+3*p1-3*p2+p3)*u3);
}
const _pv=new THREE.Vector3(), _lv=new THREE.Vector3();
function cameraAt(vt){
  const n=KEY.length;
  let i=0; while(i<D.shots.length-1 && vt>=D.shots[i+1].vt) i++;
  const t0=D.shots[i].vt, t1=(i+1<D.shots.length)?D.shots[i+1].vt:(t0+D.shots[i].dur);
  const u=Math.max(0,Math.min(1,(t1>t0)?(vt-t0)/(t1-t0):0));
  const k=(a)=>KEY[Math.max(0,Math.min(n-1,a))];
  const A=k(i-1),B=k(i),C=k(i+1),E=k(i+2);
  _pv.set(cr(A[0],B[0],C[0],E[0],u), cr(A[1],B[1],C[1],E[1],u), cr(A[2],B[2],C[2],E[2],u));
  _lv.set(cr(A[3],B[3],C[3],E[3],u), cr(A[4],B[4],C[4],E[4],u), cr(A[5],B[5],C[5],E[5],u));
  const fov=cr(A[6],B[6],C[6],E[6],u);
  return {p:_pv,l:_lv,fov:fov};
}
